 * top of this file); $base is Build #1's stage costs, stage 1 first. buildStages() in spaceOreMiner.js does the same.
 */
function hbHubMinerBuildStages(int $number, array $base): array
{
    $build = HBHUB_MINER_BUILDS[$number];
    $percent = HBHUB_MINER_BUILD_COST_FIRST + HBHUB_MINER_BUILD_COST_STEP * ($number - 3);
    $stages = [];
    foreach (HBHUB_MINER_BUILD_STAGES as $index => $plan) {
        $section = 'ABCDE'[intdiv($index, 5)];
        $fill = static fn (string $text): string => str_replace(['{name}', '{section}', '{finale}', '{crew}'],
            [$build['name'], $build['sections'][$section], $build['finale'], $build['crew']['name'] ?? ''], $text);
        $perk = $plan['perk'];
        if (isset($perk['crewText'])) {
            $perk['text'] = isset($build['crew']) ? $perk['crewText'] : $perk['text'];
            unset($perk['crewText']);
        }
        $perk['text'] = $fill($perk['text']);
        $lock = $plan['lock'];
        if ($lock !== null) {
            $lock['text'] = $fill($lock['text']);
        }
        $stages[] = [
            'name' => $index === 24 ? $build['finale']
                : ($index % 5 === 4 ? $build['sections'][$section] . ' Seal' : $build['parts'][intdiv($index, 5) * 4 + $index % 5]),
            'section' => $section,
            'cost' => intdiv($base[$index] * $percent, 100),
            'lock' => $lock,
            'perk' => $perk,
        ];
    }
    return $stages;
}
