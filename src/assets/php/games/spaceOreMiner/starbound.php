//
// Shape of a build: ['name' => string, 'hue' => 0-359, 'finale' => string, 'sections' => ['A' => string, ... 'E'],
// 'parts' => list of 20 strings, 'news' => string, 'crew' => ['name' => string, 'icon' => emoji] (optional)].

